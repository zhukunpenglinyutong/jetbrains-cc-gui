package com.github.claudecodegui.model;

import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * The agent field contract, pinned to the Claude Code subagent specification.
 *
 * <p>Field names and semantics come from code.claude.com/docs/en/claude-directory
 * ("Frontmatter fields by file", row {@code agents/*.md}) and
 * code.claude.com/docs/en/sub-agents ("Supported frontmatter fields"). The
 * documentation was cross-checked against the task PRD and the two agree
 * exactly, so the list below is the whole set: no field was dropped and none
 * was invented.
 *
 * <p>Only {@code name} and {@code description} are required by the specification;
 * everything else is optional. Per the documentation, an unrecognized field is
 * ignored without error — which is why this class is a *contract descriptor*,
 * not a whitelist used to filter data. Serialization deliberately keeps fields
 * the plugin does not model, so a store entry written by a newer Claude Code (or
 * a newer plugin) survives a read/write round trip instead of being silently
 * truncated.
 */
public final class AgentFields {

    // ------------------------------------------------------------------
    // Discovery scopes. Mirrors the skills subsystem's global/local pair,
    // plus "store" for the plugin's own ~/.codemoss/agent.json entries.
    // ------------------------------------------------------------------

    /** Agent discovered in ~/.claude/agents (user-level, available everywhere). */
    public static final String SCOPE_GLOBAL = "global";

    /** Agent discovered in {workspace}/.claude/agents (project-level). */
    public static final String SCOPE_LOCAL = "local";

    /** Agent stored in the plugin's own ~/.codemoss/agent.json. */
    public static final String SCOPE_STORE = "store";

    private static final Set<String> DISCOVERY_SCOPES =
            Set.of(SCOPE_GLOBAL, SCOPE_LOCAL, SCOPE_STORE);

    // ------------------------------------------------------------------
    // Specification fields, in documentation order.
    // ------------------------------------------------------------------

    /** The specification field set, exactly as documented for agents/*.md. */
    public static final List<String> SPECIFICATION_FIELDS = List.of(
            "name",
            "description",
            "tools",
            "disallowedTools",
            "model",
            "permissionMode",
            "maxTurns",
            "skills",
            "mcpServers",
            "hooks",
            "memory",
            "background",
            "effort",
            "isolation",
            "color",
            "initialPrompt",
            "omitClaudeMd",
            "experimental");

    /** Discovery metadata carried alongside the specification fields. */
    public static final List<String> DISCOVERY_FIELDS = List.of(
            "path",
            "scope",
            "source",
            "readOnly",
            "warning");

    /**
     * Fields owned by the plugin store rather than the specification.
     * {@code id} and {@code createdAt} are generated by the plugin and are
     * protected from updates; the rest predate subagent support.
     */
    public static final List<String> STORE_FIELDS = List.of(
            "id",
            "prompt",
            "createdAt");

    // ------------------------------------------------------------------
    // Name rules
    // ------------------------------------------------------------------

    /**
     * Hyphen-case, per the specification's own examples ("code-reviewer",
     * "reviewer-v2"). This is the *convention*, not a hard requirement: the
     * documentation states no such constraint, and real stores plus the
     * developer's machine contain names like "New Agent". So a name that
     * deviates is accepted and merely flagged, never dropped.
     */
    private static final Pattern HYPHEN_CASE = Pattern.compile("^[a-z0-9]+(-[a-z0-9]+)*$");

    /**
     * The one character the specification actually forbids. ':' is reserved for
     * plugin-scoped identifiers ("my-plugin:reviewer"); Claude Code refuses to
     * load a file whose name contains one. Everything else — spaces, uppercase,
     * underscores, and any length — is permitted.
     */
    private static final Pattern FORBIDDEN_NAME_CHARS = Pattern.compile("[:\\r\\n]");

    /**
     * The former 1-20 character name cap. The specification documents no length
     * limit, and the cap rejected 16 real agents on the developer's machine
     * (e.g. "seo-cannibalization-detector", 28 characters). It was removed.
     * This constant survives only as the floor: a name must have some content.
     */
    public static final int MIN_NAME_LENGTH = 1;

    private AgentFields() {
    }

    /**
     * Check whether a name is a valid agent identifier per the specification.
     * Length is deliberately unbounded.
     *
     * @param name the candidate name
     * @return true when the name is non-blank and free of reserved characters
     */
    public static boolean isValidName(String name) {
        if (name == null) {
            return false;
        }
        String trimmed = name.trim();
        return trimmed.length() >= MIN_NAME_LENGTH
                && !FORBIDDEN_NAME_CHARS.matcher(trimmed).find();
    }

    /**
     * Check whether a name deviates from the hyphen-case convention.
     *
     * <p>A {@code true} result is a non-blocking warning: the name still works,
     * it simply is not what the specification's examples look like. Returning a
     * boolean rather than rejecting keeps names such as "New Agent" — which
     * exist in real stores — usable while letting the UI explain the deviation.
     *
     * @param name the agent name
     * @return true when the name is not hyphen-case
     */
    public static boolean isNonHyphenCaseName(String name) {
        if (name == null) {
            return false;
        }
        return !HYPHEN_CASE.matcher(name.trim()).matches();
    }

    /**
     * Convert a name into a filesystem- and id-safe segment.
     *
     * <p>Used when a discovered file name has to become an id. Only used for id
     * generation — the name itself is never rewritten, because a name is a
     * display identifier and altering it would break the link back to the file.
     *
     * @param name the agent name
     * @return the name with spaces converted to hyphens
     */
    public static String toIdSegment(String name) {
        if (name == null) {
            return "";
        }
        return name.trim().replaceAll("\\s+", "-");
    }

    /**
     * Check whether a value is a known discovery scope.
     *
     * @param scope the scope value
     * @return true for "global", "local" or "store"
     */
    public static boolean isDiscoveryScope(String scope) {
        return DISCOVERY_SCOPES.contains(scope);
    }
}
