    private static final long TWO_HOURS_MS = TimeUnit.HOURS.toMillis(2);
    private static final long THREE_HOURS_MS = TimeUnit.HOURS.toMillis(3);

    @Test
    public void decisionStoreRemembersToolAndParameterScopesIndependently() {
        PermissionDecisionStore store = new PermissionDecisionStore();
        JsonObject editInputs = new JsonObject();
        editInputs.addProperty("file_path", "/tmp/demo.txt");

        assertEquals(null, store.getToolDecision("Edit"));
        assertEquals(null, store.getParameterDecision("Edit", editInputs));

        store.rememberParameterDecision("Edit", editInputs, PermissionService.PermissionResponse.ALLOW_ALWAYS);
        assertEquals(
                PermissionService.PermissionResponse.ALLOW_ALWAYS,
                store.getParameterDecision("Edit", editInputs)
        );

        store.rememberToolDecision("Edit", PermissionService.PermissionResponse.ALLOW_ALWAYS);
        assertEquals(PermissionService.PermissionResponse.ALLOW_ALWAYS, store.getToolDecision("Edit"));
        assertEquals(1, store.getToolMemorySize());
        assertEquals(1, store.getParameterMemorySize());

        store.clear();
        assertEquals(0, store.getToolMemorySize());
        assertEquals(0, store.getParameterMemorySize());
    }

    @Test
    public void toolLevelAlwaysAllowIsHonoredForCommandTools() {
        // Regression for v0.4.6 (E): "Always allow" for Bash/Agent was scoped away from the
        // tool level, so a single approval no longer suppressed later prompts and users had to
        // confirm every command. v0.4.7 restores the v0.4.5 "confirm once" behavior — a
        // tool-level ALLOW_ALWAYS for Bash must be honored, not suppressed to null.
        PermissionDecisionStore store = new PermissionDecisionStore();
        assertEquals(null, store.getToolDecision("Bash"));

        store.rememberToolDecision("Bash", PermissionService.PermissionResponse.ALLOW_ALWAYS);
        assertEquals(
                PermissionService.PermissionResponse.ALLOW_ALWAYS,
                store.getToolDecision("Bash")
        );

        // A tool-level DENY is still honored for command tools (deny is the safe direction).
        store.rememberToolDecision("Agent", PermissionService.PermissionResponse.DENY);
        assertEquals(PermissionService.PermissionResponse.DENY, store.getToolDecision("Agent"));
    }

    @Test
    public void commandLevelMemoryIgnoresVolatileDescription() {
        // Regression: parameter-level memory keyed on the full input JSON never re-matched,
        // because Bash "description" is regenerated by the model every turn. The key must
        // depend on the command string alone so the very same command re-hits its decision.
        PermissionDecisionStore store = new PermissionDecisionStore();

        JsonObject first = new JsonObject();
        first.addProperty("command", "git status");
        first.addProperty("description", "Check current git status");
        store.rememberParameterDecision("Bash", first, PermissionService.PermissionResponse.ALLOW_ALWAYS);

        // Same command, different model-generated description → must still hit.
        JsonObject second = new JsonObject();
        second.addProperty("command", "git status");
        second.addProperty("description", "Show the working tree status");
        assertEquals(
                PermissionService.PermissionResponse.ALLOW_ALWAYS,
                store.getParameterDecision("Bash", second)
        );

        // A genuinely different command must NOT hit it.
        JsonObject other = new JsonObject();
        other.addProperty("command", "git push");
        other.addProperty("description", "Check current git status");
        assertEquals(null, store.getParameterDecision("Bash", other));
    }

    @Test
    public void fileProtocolCleanupRemovesOnlyCurrentSessionFiles() throws IOException {
        Path permissionDir = Files.createTempDirectory("permission-protocol-cleanup");
        try {
            PermissionFileProtocol protocol = new PermissionFileProtocol(
                    permissionDir,
                    "session-a",
                    new Gson(),
                    (tag, message) -> {
                    }
            );

            Path ownResponse = Files.writeString(permissionDir.resolve("response-session-a-1.json"), "{}");
            Path ownRequest = Files.writeString(permissionDir.resolve("request-session-a-2.json"), "{}");
            Path ownAsk = Files.writeString(permissionDir.resolve("ask-user-question-session-a-3.json"), "{}");
            Path ownAskResponse = Files.writeString(
                    permissionDir.resolve("ask-user-question-response-session-a-3.json"), "{}");
            Path ownPlan = Files.writeString(permissionDir.resolve("plan-approval-session-a-4.json"), "{}");
            Path ownPlanResponse = Files.writeString(
                    permissionDir.resolve("plan-approval-response-session-a-4.json"), "{}");
            Path otherSession = Files.writeString(permissionDir.resolve("response-session-b-1.json"), "{}");
            Path unrelated = Files.writeString(permissionDir.resolve("notes.txt"), "keep");

            protocol.cleanupSessionFiles();

            assertFalse(Files.exists(ownResponse));
            assertFalse(Files.exists(ownRequest));
            assertFalse(Files.exists(ownAsk));
            assertFalse(Files.exists(ownAskResponse));
            assertFalse(Files.exists(ownPlan));
            assertFalse(Files.exists(ownPlanResponse));
            assertTrue(Files.exists(otherSession));
            assertTrue(Files.exists(unrelated));
        } finally {
            deleteDirectory(permissionDir);
        }
    }

    @Test
    public void fileProtocolStaleCleanupKeepsFreshFilesAndRemovesExpiredOnes() throws IOException {
        Path permissionDir = Files.createTempDirectory("permission-protocol-stale-cleanup");
        try {
            PermissionFileProtocol protocol = new PermissionFileProtocol(
                    permissionDir,
                    "session-a",
                    new Gson(),
                    (tag, message) -> {
                    }
            );

            long now = System.currentTimeMillis();
            Path freshAsk = Files.writeString(
                    permissionDir.resolve("ask-user-question-session-a-fresh.json"), "{\"fresh\":true}");
            Path staleAsk = Files.writeString(
                    permissionDir.resolve("ask-user-question-session-a-stale.json"), "{\"stale\":true}");
            Path staleOtherSession = Files.writeString(
                    permissionDir.resolve("ask-user-question-session-b-stale.json"), "{}");
            Files.setLastModifiedTime(freshAsk, FileTime.fromMillis(now));
            Files.setLastModifiedTime(staleAsk, FileTime.fromMillis(now - THREE_HOURS_MS));
            Files.setLastModifiedTime(staleOtherSession, FileTime.fromMillis(now - THREE_HOURS_MS));

            protocol.cleanupStaleSessionFiles(TWO_HOURS_MS);

            assertTrue("fresh request must survive watcher-start stale cleanup", Files.exists(freshAsk));
            assertFalse("expired request for this session must be removed", Files.exists(staleAsk));
            assertTrue("other session files must never be touched", Files.exists(staleOtherSession));
        } finally {
            deleteDirectory(permissionDir);
        }
    }

